class ComplexityEngine:
    """Computes Big-O Time & Space complexity from Flowchart IR."""

    @classmethod
    def analyze(cls, ir: FlowchartIR) -> ComplexityAnalysis:
        has_loop = False
        loop_count = 0
        has_branch = False

        # Detect cycles/loops via backward edges in topological ordering
        for e in ir.edges:
            if e.target_id <= e.source_id:
                has_loop = True
                loop_count += 1

        for n in ir.nodes:
            if n.node_type == FlowNodeType.DECISION:
                has_branch = True

        if loop_count > 1:
            time_c = "O(N²)"
            reason = "Multiple nested loops or backward flow cycles detected in diagram."
        elif has_loop:
            time_c = "O(N)"
            reason = "Single iteration loop with linear recurrence detected."
        elif has_branch:
            time_c = "O(1)"
            reason = "Constant time with conditional branches (if-else tree)."
        else:
            time_c = "O(1)"
            reason = "Linear sequential instructions with direct execution path."

        space_c = "O(1)"
        space_reason = f"Allocates {len(ir.variables)} scalar primitive variables ({', '.join(ir.variables) if ir.variables else 'none'})."

        return ComplexityAnalysis(
            time_complexity=time_c,
            space_complexity=space_c,
            reasoning=f"Time: {reason} | Space: {space_reason}",
            bottlenecks=["I/O console wait time"] if ir.variables else ["None"],
            optimizations=["Use vectorization if scaling to arrays", "Inline static constants"],
        )


class TestSuiteGenerator:
    """Generates 5+ parameterized test cases with boundary & edge inputs."""

    @classmethod
    def generate(cls, ir: FlowchartIR) -> List[Dict[str, Any]]:
        tests = []
        vars_count = len(ir.variables) if ir.variables else 1

        # 1. Standard positive input
        tests.append({
            "id": 1,
            "name": "Standard Positive Input",
            "input": "15\n" * vars_count,
            "expected_behavior": "Valid positive execution branch",
            "category": "Normal Case",
        })

        # 2. Zero boundary input
        tests.append({
            "id": 2,
            "name": "Zero Boundary Value",
            "input": "0\n" * vars_count,
            "expected_behavior": "Boundary threshold test (0)",
            "category": "Boundary",
        })

        # 3. Negative input
        tests.append({
            "id": 3,
            "name": "Negative Integer Input",
            "input": "-42\n" * vars_count,
            "expected_behavior": "Valid negative execution branch",
            "category": "Edge Case",
        })

        # 4. Large scale number
        tests.append({
            "id": 4,
            "name": "Large Value (Stress Test)",
            "input": "9999999\n" * vars_count,
            "expected_behavior": "No integer overflow, handles large float",
            "category": "Stress Test",
        })

        # 5. Floating point fractional input
        tests.append({
            "id": 5,
            "name": "Floating Point Decimal",
            "input": "3.14159\n" * vars_count,
            "expected_behavior": "Handles decimal precision correctly",
            "category": "Precision Test",
        })

        return tests


class CodeGenerator:
    """
    Main Code Generation Facade.
    Combines Deterministic Transpilation, AI Generation (optional), Complexity Analysis, and Unit Tests.
    """

    def __init__(self, api_key: Optional[str] = None, provider: str = "none"):
        self.api_key = api_key
        self.provider = provider.lower()

    def generate(self, ir: FlowchartIR, active_language: str = "Python") -> GeneratedCodeResult:
        """Produces full polyglot output with complexity analysis and test cases."""
        # 1. Generate multi-language code using deterministic builder
        codes = DeterministicCodeBuilder.generate_all(ir)
        engine_used = "Deterministic AST Engine"

        # 2. If API Key provided, attempt AI refinement
        if self.api_key and self.provider in ["gemini", "openai"]:
            ai_code = self._try_ai_refinement(ir, active_language)
            if ai_code:
                codes[active_language] = ai_code
                engine_used = f"AI / LLM Engine ({self.provider.upper()})"

        # 3. Compute Big-O complexity
        complexity = ComplexityEngine.analyze(ir)

        # 4. Generate line-by-line explanations
        explanations = self._generate_explanations(ir)

        # 5. Generate Unit Test Suite
        test_cases = TestSuiteGenerator.generate(ir)

        return GeneratedCodeResult(
            codes=codes,
            active_language=active_language,
            complexity=complexity,
            line_explanations=explanations,
            test_cases=test_cases,
            engine_used=engine_used,
        )

    def _generate_explanations(self, ir: FlowchartIR) -> List[Dict[str, Any]]:
        exps = []
        for n in ir.nodes:
            exps.append({
                "node_id": n.id,
                "shape": n.shape,
                "type": n.node_type.value,
                "text": n.raw_text,
                "explanation": f"Node #{n.id} ({n.node_type.value}): Translates to '{n.cleaned_expression}' logic in target language.",
            })
        return exps

    def _try_ai_refinement(self, ir: FlowchartIR, lang: str) -> Optional[str]:
        """Calls OpenAI or Gemini API if credentials are supplied."""
        prompt = f"""
        Convert this structured flowchart IR into clean, production-grade {lang} code:
        {ir.to_json()}
        Return ONLY valid {lang} code, without markdown quotes or explanation.
        """
        try:
            if self.provider == "gemini":
                import google.generativeai as genai
                genai.configure(api_key=self.api_key)
                model = genai.GenerativeModel("gemini-1.5-flash")
                response = model.generate_content(prompt)
                return response.text.replace("```python", "").replace("```cpp", "").replace("```java", "").replace("```javascript", "").replace("```", "").strip()
            elif self.provider == "openai":
                import openai
                client = openai.OpenAI(api_key=self.api_key)
                response = client.chat.completions.create(
                    model="gpt-4o-mini",
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.2,
                )
                return response.choices[0].message.content.replace("```python", "").replace("```", "").strip()
        except Exception:
            return None
        return None
